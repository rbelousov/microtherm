"""Markov-chain evolution of a Boltzmann gas.

The state is represented by occupation probabilities p[ell, i], where ell is a
lattice site and i is an energy level. The dynamics is generated by a transition
probability tensor

    P[ell, i, m, j]

for transitions from the source state J = (m, j) to the destination state
I = (ell, i).

The transition tensor is constructed from structural weights w[ell, i, m, j]
according to the microcaliber form

    P_IJ = w_IJ exp[-beta_ell (epsilon_I - epsilon_J)] / zeta_J,

with zeta_J chosen so that sum_I P_IJ = 1 for every source state J.
"""

import json
import warnings
from pathlib import Path
from collections.abc import Callable
from typing import Any, ClassVar, TypeAlias, Self, BinaryIO, cast
import copy

import numpy as np
import numpy.typing as npt
from scipy.optimize import root_scalar
from .connectivity import nearest_neighbor_weights, transition_tensor


def energy_levels(nlevels: int, scale: float = 1.0) -> npt.NDArray[np.floating]:
    """Return the default kinetic energy levels epsilon_i = scale * i^2 / 2.

    Args:
        nlevels: Number of energy levels.
        scale: Energy scale multiplying i^2 / 2.

    Returns:
        One-dimensional array of energy levels.
    """
    if nlevels <= 0:
        raise ValueError(f"nlevels must be positive, got {nlevels}")
    return scale * np.arange(1, nlevels + 1, dtype=float) ** 2 / 2.0


class State:
    """State of the Boltzmann gas.

    Attributes:
        levels: Occupation probabilities p[ell, i].
        betas: Inverse temperatures beta[ell].
        transition: Transition tensor from the previous update, or None.
        meta: JSON-serializable metadata.
    """

    def __init__(
        self,
        nsites: int | None = None,
        levels: npt.ArrayLike | None = None,
        betas: npt.ArrayLike | None = None,
        transition: npt.ArrayLike | None = None,
        meta: dict[str, Any] | None = None,
    ):
        """Create a state.

        Args:
            nsites: Number of lattice sites. Required when neither levels nor
                betas are provided.
            levels: Occupation probabilities p[ell, i].
            betas: Inverse temperatures beta[ell].
            transition: Transition tensor from the previous update.
            meta: JSON-serializable metadata.
        """
        if levels is None and betas is None:
            if nsites is None:
                raise ValueError("levels, betas, or nsites must be provided")
        elif levels is not None:
            nsites = len(cast(np.ndarray, levels))
        else:
            nsites = len(cast(np.ndarray, betas))

        assert nsites is not None

        self.levels = (
            np.zeros((nsites, nsites), dtype=float)
            if levels is None
            else np.array(levels, dtype=float, copy=True)
        )
        self.betas = (
            np.zeros(nsites, dtype=float)
            if betas is None
            else np.array(betas, dtype=float, copy=True)
        )
        self.transition = (
            None if transition is None else np.array(transition, dtype=float, copy=True)
        )
        self.meta = {} if meta is None else dict(meta)

        self._validate()

    def _validate(self) -> None:
        """Validate the state attributes."""
        if self.levels.ndim != 2:
            raise ValueError(f"levels must be two-dimensional, got {self.levels.ndim}D")
        if self.betas.shape != (self.levels.shape[0],):
            raise ValueError(
                f"betas must have shape ({self.levels.shape[0]},), got {self.betas.shape}"
            )
        if np.any(self.levels < 0):
            raise ValueError("levels must be nonnegative")

    def __len__(self) -> int:
        """Return the lattice size."""
        return self.levels.shape[0]

    @property
    def nlevels(self) -> int:
        """Return the number of energy levels."""
        return self.levels.shape[1]

    def site_occupancies(self) -> npt.NDArray[np.floating]:
        """Return site occupation probabilities."""
        return self.levels.sum(axis=1)

    def site_energies(
        self, energies: npt.ArrayLike | None = None
    ) -> npt.NDArray[np.floating]:
        """Return site energies E[ell] = sum_i epsilon_i p[ell, i]."""
        eps = energy_levels(self.nlevels) if energies is None else np.asarray(energies)
        return np.dot(self.levels, eps)

    def energy_profile(
        self, energies: npt.ArrayLike | None = None
    ) -> npt.NDArray[np.floating]:
        """Return the normalized site-energy profile."""
        site_energies = self.site_energies(energies)
        total = site_energies.sum()
        if total <= 0:
            return np.zeros_like(site_energies)
        return site_energies / total

    def normalize(self) -> None:
        """Normalize occupation probabilities in place."""
        total = self.levels.sum()
        if total <= 0:
            raise ValueError("cannot normalize a state with zero total occupation")
        self.levels /= total

    @classmethod
    def from_gas_levels(
        cls,
        gas_levels: dict[str, list[int]],
        nsites: int | None = None,
        nlevels: int | None = None,
        betas: npt.ArrayLike | None = None,
        meta: dict[str, Any] | None = None,
    ) -> Self:
        """Create a Boltzmann-gas state from particle site/energy assignments.

        Args:
            gas_levels: Mapping returned by `microtherm.gas.State.levels`:
                `particle_id -> [site, level]`.
            nsites: Number of sites. If omitted, inferred from the largest
                observed site index.
            nlevels: Number of energy levels. If omitted, inferred from the
                largest observed level index.
            betas: Optional inverse-temperature profile.
            meta: Optional JSON-serializable metadata.

        Returns:
            State with normalized occupation probabilities.
        """
        if not gas_levels:
            raise ValueError("gas_levels must contain at least one particle")

        values = list(gas_levels.values())
        if any(len(assignment) != 2 for assignment in values):
            raise ValueError("gas_levels values must be [site, level] pairs")

        try:
            assignments_float = np.array(values, dtype=float)
        except (TypeError, ValueError) as exc:
            raise ValueError("site and level indices must be numeric") from exc

        if assignments_float.ndim != 2 or assignments_float.shape[1] != 2:
            raise ValueError("gas_levels values must be [site, level] pairs")
        if not np.all(np.isfinite(assignments_float)):
            raise ValueError("site and level indices must be finite")
        if np.any(assignments_float < 0):
            raise ValueError("site and level indices must be nonnegative")
        if np.any(assignments_float != np.floor(assignments_float)):
            raise ValueError("site and level indices must be integers")

        assignments = assignments_float.astype(int)
        required_sites = int(assignments[:, 0].max()) + 1
        required_levels = int(assignments[:, 1].max()) + 1

        if nsites is None:
            nsites = required_sites
        elif nsites <= 0:
            raise ValueError(f"nsites must be positive, got {nsites}")
        elif required_sites > nsites:
            raise ValueError(
                f"gas_levels contains site index {required_sites - 1}, outside nsites={nsites}"
            )

        if nlevels is None:
            nlevels = required_levels
        elif nlevels <= 0:
            raise ValueError(f"nlevels must be positive, got {nlevels}")
        elif required_levels > nlevels:
            raise ValueError(
                "gas_levels contains level index "
                f"{required_levels - 1}, outside nlevels={nlevels}"
            )

        levels = np.zeros((nsites, nlevels), dtype=float)
        np.add.at(levels, (assignments[:, 0], assignments[:, 1]), 1.0)
        levels /= len(gas_levels)

        return cls(levels=levels, betas=betas, meta=meta)

    def save(self, path: str | Path | BinaryIO) -> None:
        """Save the state to a NumPy .npz file."""
        data: dict[str, Any] = {
            "levels": self.levels,
            "betas": self.betas,
            "transition": self.transition,
        }
        if self.meta:
            data["meta"] = json.dumps(self.meta)
        np.savez(path, **data)

    @classmethod
    def load(cls, path: str | Path | BinaryIO) -> Self:
        """Load a state from a NumPy .npz file.

        Returns:
            A State instance with the loaded data.
        """
        data = np.load(path, allow_pickle=True)
        transition = data["transition"] if "transition" in data else None
        if transition is not None and transition.shape == () and transition[()] is None:
            transition = None
        meta = json.loads(str(data["meta"])) if "meta" in data else {}
        return cls(
            levels=data["levels"],
            betas=data["betas"],
            transition=transition,
            meta=meta,
        )


class Model:
    """Boltzmann-gas Markov-chain model.

    The model advances the state by constructing a transition tensor from fixed
    dynamical weights and the inverse-temperature field beta[ell]. In the bulk,
    beta[ell] is determined by the local energy-balance condition

        sum_{i,m,j} P[ell, i, m, j] p[m, j] (epsilon_j - epsilon_i) = 0.

    Boundary sites may instead have fixed inverse temperatures.

    Attributes:
        state: Current state of the model.
        fixed: Mapping from site index to fixed inverse temperature.
        tol: Tolerance for energy-balance residuals.
        beta_tol: Scalar root-finding tolerance for beta values.
        beta_bracket: Maximum absolute beta used while expanding brackets.
        maxiter: Maximum number of Gauss-Seidel sweeps.
        energies: Energy levels epsilon[i].
        weights: Structural weights w[ell, i, m, j] for the transition tensor.
        degeneracy: Optional destination degeneracies g[i] or g[ell, i].
    """

    State: ClassVar[TypeAlias] = State

    def __init__(
        self,
        state: State,
        connectivity: npt.ArrayLike | None = None,
        fixed_betas: dict[int, float] | None = None,
        energies: npt.ArrayLike | None = None,
        degeneracy: npt.ArrayLike | None = None,
        tol: float = 1e-12,
        beta_tol: float = 1e-12,
        beta_bracket: float = 10.0,
        maxiter: int = 100,
    ):
        """Create a model.

        Args:
            state: Initial state.
            connectivity: Either a 4D array of structural weights w[ell, i, m, j] or None to use the nearest-neighbor connectivity
            fixed_betas: Mapping from site index to fixed inverse temperature.
                Typically used for the two thermalizing boundary reservoirs.
            energies: Energy levels epsilon[i]. Defaults to i^2 / 2.
            degeneracy: Optional destination degeneracies g[i] or g[ell, i].
                Omit this if degeneracies are already included in the weights.
            tol: Tolerance for energy-balance residuals.
            beta_tol: Scalar root-finding tolerance for beta values.
            beta_bracket: Maximum absolute beta used while expanding brackets.
            maxiter: Maximum number of Gauss-Seidel sweeps.
        """
        self.state = state
        self.fixed = {} if fixed_betas is None else dict(fixed_betas)
        self.tol = float(tol)
        self.beta_tol = float(beta_tol)
        self.beta_bracket = float(beta_bracket)
        self.maxiter = int(maxiter)

        nsites = len(state)
        nlevels = state.nlevels
        self.energies = (
            energy_levels(nlevels)
            if energies is None
            else np.array(energies, dtype=float, copy=True)
        )
        if self.energies.shape != (nlevels,):
            raise ValueError(
                f"energies must have shape ({nlevels},), got {self.energies.shape}"
            )

        self.weights = self._init_weights(connectivity, nsites, nlevels)
        self.degeneracy = (
            None if degeneracy is None else np.array(degeneracy, dtype=float, copy=True)
        )
        self._validate_degeneracy(nsites, nlevels)

    @staticmethod
    def _init_weights(
        connectivity: npt.ArrayLike | None, nsites: int, nlevels: int
    ) -> np.ndarray:
        if connectivity is None:
            weights = np.array(
                nearest_neighbor_weights(nsites, nlevels), dtype=float, copy=True
            )
        else:
            weights = np.array(connectivity, dtype=float, copy=True)

        expected = (nsites, nlevels, nsites, nlevels)
        if weights.shape != expected:
            raise ValueError(f"weights must have shape {expected}, got {weights.shape}")
        if np.any(weights < 0):
            raise ValueError("weights must be nonnegative")
        if np.any(weights.sum(axis=(0, 1)) <= 0):
            raise ValueError(
                "every source state must have at least one outgoing transition"
            )
        return weights

    def _validate_degeneracy(self, nsites: int, nlevels: int) -> None:
        if self.degeneracy is None:
            return
        if self.degeneracy.shape not in {(nlevels,), (nsites, nlevels)}:
            raise ValueError(
                f"degeneracy must have shape ({nlevels},) or ({nsites}, {nlevels}), "
                f"got {self.degeneracy.shape}"
            )
        if np.any(self.degeneracy < 0):
            raise ValueError("degeneracy must be nonnegative")

    def build_transition(self, betas: npt.ArrayLike) -> np.ndarray:
        """Build P[ell, i, m, j] for the supplied inverse temperatures."""
        return transition_tensor(
            self.weights,
            np.asarray(betas, dtype=float),
            self.energies,
            degeneracy=self.degeneracy,
        )

    def local_equilibrium(
        self,
        betas: npt.ArrayLike | None = None,
    ) -> npt.NDArray[np.floating]:
        """Return local-equilibrium energy distributions at each site.

        For each site `ell` this computes the conditional Boltzmann
        distribution over energy levels,

            q[ell, i] = g[ell, i] exp(-beta[ell] epsilon[i]) / z[ell],

        where `z[ell]` is the local partition function. If `betas` is
        omitted, the current `state.betas` are used. The optional model
        `degeneracy` may have shape `(nlevels,)` or `(nsites, nlevels)`;
        if it is omitted, all degeneracies are treated as one.

        Args:
            betas: Optional inverse-temperature profile with one value per site.

        Returns:
            Array `q[ell, i]` with shape matching `state.levels`. Each row
            sums to one.

        Raises:
            ValueError: If the beta profile, energy levels, or degeneracies have incompatible shapes, if degeneracies are negative, or if a local partition function is zero.
        """
        levels = np.asarray(self.state.levels, dtype=float)
        beta_profile = (
            np.asarray(self.state.betas, dtype=float)
            if betas is None
            else np.asarray(betas, dtype=float)
        )
        energies = np.asarray(self.energies, dtype=float)

        if levels.ndim != 2:
            raise ValueError(f"levels must be two-dimensional, got {levels.ndim}D")

        nsites, nlevels = levels.shape

        if beta_profile.shape != (nsites,):
            raise ValueError(
                f"betas must have shape ({nsites},), got {beta_profile.shape}"
            )
        if energies.shape != (nlevels,):
            raise ValueError(
                f"energies must have shape ({nlevels},), got {energies.shape}"
            )

        logq = -beta_profile[:, None] * energies[None, :]

        if self.degeneracy is not None:
            degeneracy = np.asarray(self.degeneracy, dtype=float)
            if np.any(degeneracy < 0.0):
                raise ValueError("degeneracy must be nonnegative")

            if degeneracy.shape == (nlevels,):
                log_degeneracy = np.full_like(degeneracy, -np.inf, dtype=float)
                positive = degeneracy > 0.0
                log_degeneracy[positive] = np.log(degeneracy[positive])
                logq = logq + log_degeneracy[None, :]
            elif degeneracy.shape == (nsites, nlevels):
                log_degeneracy = np.full_like(degeneracy, -np.inf, dtype=float)
                positive = degeneracy > 0.0
                log_degeneracy[positive] = np.log(degeneracy[positive])
                logq = logq + log_degeneracy
            else:
                raise ValueError(
                    "degeneracy must have shape "
                    f"({nlevels},) or ({nsites}, {nlevels}), got {degeneracy.shape}"
                )

        finite = np.isfinite(logq)
        if np.any(~np.any(finite, axis=1)):
            raise ValueError(
                "local-equilibrium partition function is zero at one or more sites"
            )

        max_logq = np.max(np.where(finite, logq, -np.inf), axis=1, keepdims=True)
        q_unnormalized = np.where(finite, np.exp(logq - max_logq), 0.0)
        return q_unnormalized / q_unnormalized.sum(axis=1, keepdims=True)

    def local_equilibrium_kl(
        self,
        normalize_by_site: bool = True,
        atol: float = 0.0,
    ) -> npt.NDArray[np.floating]:
        """Return the local-equilibrium KL divergence at each site.

        For each site ell, this computes

            D_KL[p(i | ell) || q_beta(i | ell)]

        where p(i | ell) is the current conditional distribution over energy
        levels at site ell, and q_beta is the local Boltzmann distribution.

        Args:
            normalize_by_site: If True, compare conditional distributions over
                energy levels at each site. If False, compare unnormalized site
                contributions p[ell, i] against rho[ell] q_beta(i | ell),
                where rho[ell] is the site occupancy. The resulting value is
                weighted by rho[ell].
            atol: Small cutoff used to ignore tiny negative values from numerical
                noise. Values below -atol still raise an error.

        Returns:
            One-dimensional array kl[ell]. Empty sites return NaN when
            normalize_by_site=True and 0 when normalize_by_site=False.
        """
        levels = np.asarray(self.state.levels, dtype=float)

        if levels.ndim != 2:
            raise ValueError(f"levels must be two-dimensional, got {levels.ndim}D")
        if np.any(levels < -atol):
            raise ValueError("levels must be nonnegative")

        safe_levels = np.where(levels > 0.0, levels, 0.0)
        occupancies = safe_levels.sum(axis=1)
        q = self.local_equilibrium()

        nsites = levels.shape[0]
        kl = np.full(nsites, np.nan if normalize_by_site else 0.0, dtype=float)

        occupied = occupancies > 0.0
        if not np.any(occupied):
            return kl

        if normalize_by_site:
            p = safe_levels[occupied] / occupancies[occupied, None]
            reference = q[occupied]
        else:
            p = safe_levels[occupied]
            reference = q[occupied] * occupancies[occupied, None]

        mask = p > 0.0
        terms = np.zeros_like(p)
        terms[mask] = p[mask] * (np.log(p[mask]) - np.log(reference[mask]))
        kl[occupied] = terms.sum(axis=1)

        return kl

    def site_transition(
        self,
        betas: npt.ArrayLike | None = None,
    ) -> npt.NDArray[np.floating]:
        """Return the local-equilibrium site-to-site transition kernel.

        This evaluates

            P_site[ell, m] = sum_{i,j} P[ell, i, m, j] q[m, j],

        where `q` is the local-equilibrium distribution at the source site
        `m`. If `betas` is omitted, the current `state.betas` are used.
        """
        beta_profile = (
            np.asarray(self.state.betas, dtype=float)
            if betas is None
            else np.asarray(betas, dtype=float)
        )
        q = self.local_equilibrium(beta_profile)
        transition = self.build_transition(beta_profile)
        return np.einsum("limj,mj->lm", transition, q, optimize=True)

    def energy_balance(self, betas: npt.ArrayLike) -> npt.NDArray[np.floating]:
        """Return the site-wise energy-balance residuals.

        For each destination site ell, this evaluates

            B_ell = sum_{i,m,j} P[ell, i, m, j] p[m, j]
                    (epsilon_j - epsilon_i).

        The microcanonical bulk condition is B_ell = 0. Fixed boundary betas are
        not altered by this method; the caller decides which residuals to solve.
        """
        transition = self.build_transition(betas)
        delta = self.energies[None, :] - self.energies[:, None]
        return np.einsum(
            "limj,mj,ij->l",
            transition,
            self.state.levels,
            delta,
            optimize=True,
        )

    def find_betas(
        self,
        grow: float = 2.0,
        relax_beta: float = 1.0,
        verbose: bool = False,
    ) -> npt.NDArray[np.floating]:
        """Find inverse temperatures satisfying bulk energy balance.

        Boundary values listed in `fixed_betas` are kept fixed. All other beta
        values are updated by a Gauss-Seidel sequence of scalar bracketing solves.
        """
        nsites = len(self.state)
        betas = np.array(self.state.betas, dtype=float, copy=True)

        for idx, value in self.fixed.items():
            if idx < 0 or idx >= nsites:
                raise ValueError(f"fixed beta index {idx} is outside [0, {nsites})")
            betas[idx] = float(value)

        free = np.array([idx for idx in range(nsites) if idx not in self.fixed])
        if free.size == 0:
            return betas

        def balance(beta: float, site: int, current_betas: np.ndarray) -> float:
            trial = current_betas.copy()
            trial[site] = float(beta)
            return float(self.energy_balance(trial)[site])

        max_dev = np.inf
        for sweep in range(self.maxiter):
            for site in free:
                residual = balance(cast(float, betas[site]), int(site), betas)
                if abs(residual) < self.tol:
                    continue

                a, b = self._initial_bracket(float(betas[site]))
                fa = balance(a, int(site), betas)
                fb = balance(b, int(site), betas)

                a, b, fa, fb = self._expand_bracket(
                    a,
                    b,
                    fa,
                    fb,
                    lambda x: balance(x, int(site), betas),
                    grow=grow,
                )

                if fa * fb > 0.0:
                    if verbose:
                        warnings.warn(
                            f"Sweep {sweep}: failed to bracket beta at site {site}; "
                            f"residual={residual:g}"
                        )
                    continue

                sol = root_scalar(
                    balance,
                    args=(int(site), betas),
                    method="brentq",
                    bracket=(a, b),
                    xtol=self.beta_tol,
                    maxiter=200,
                )
                if sol.converged:
                    beta_new = float(sol.root)
                    betas[site] = (1.0 - relax_beta) * betas[
                        site
                    ] + relax_beta * beta_new
                elif verbose:
                    warnings.warn(
                        f"Sweep {sweep}: beta solve did not converge at site {site}"
                    )

            residuals = self.energy_balance(betas)[free]
            max_dev = float(np.max(np.abs(residuals)))
            if max_dev < self.tol:
                return betas

        warnings.warn(f"Energy balance is not exact; max residual is {max_dev:g}")
        return betas

    def _initial_bracket(self, beta: float) -> tuple[float, float]:
        """Return an initial bracket [a, b] for root finding."""
        half_width = 1.0
        return beta - half_width, beta + half_width

    def _expand_bracket(
        self,
        a: float,
        b: float,
        fa: float,
        fb: float,
        func: Callable[[float], float],
        *,
        grow: float,
    ) -> tuple[float, float, float, float]:
        """Expand the bracket [a, b] until it contains a root or reaches the beta_bracket limit."""
        while fa * fb > 0.0 and (
            abs(a) < self.beta_bracket or abs(b) < self.beta_bracket
        ):
            width = b - a
            a = max(-self.beta_bracket, a - grow * width / 2.0)
            b = min(self.beta_bracket, b + grow * width / 2.0)
            fa = func(a)
            fb = func(b)
            if a <= -self.beta_bracket and b >= self.beta_bracket:
                break
        return a, b, fa, fb

    def __call__(self, **kwargs: Any) -> State:
        """Advance the model by one Markov-chain step."""
        betas = self.find_betas(**kwargs)
        transition = self.build_transition(betas)
        levels = np.einsum(
            "limj,mj->li",
            transition,
            self.state.levels,
            optimize=True,
        )
        total = levels.sum()
        if total <= 0:
            raise RuntimeError("transition produced zero total occupation")
        levels /= total

        self.state = State(
            levels=levels,
            betas=betas,
            transition=transition,
            meta=copy.deepcopy(self.state.meta),
        )
        return self.state

    def linear_thermodiffusion(self, beta: float, delta: float = 1e-5):
        """Return linear-response diffusion and thermal-diffusion coefficients.

        Args:
            beta: Reference inverse temperature.
            delta: Small perturbation of the inverse temperature.

        Returns:
            A pair `(thermal, diffusive)` of one-dimensional arrays indexed by site `ell`.
        """

        beta = float(beta)
        delta = float(delta)

        nsites = len(self.state)
        dx = 1.0 / nsites
        dt = dx

        sites = np.arange(nsites, dtype=float)
        displacement = dx * (sites[None, :] - sites[:, None])

        betas0 = np.full(nsites, beta)
        betasp = np.full(nsites, beta + delta)
        betasm = np.full(nsites, beta - delta)
        kernel0 = self.site_transition(betas0)
        kernelp = self.site_transition(betasp)
        kernelm = self.site_transition(betasm)

        sigma_d = 0.5 * np.sum(displacement**2 * kernel0, axis=1)

        dkernel = (kernelp - kernelm) / (2.0 * delta)
        sigma_t = 0.5 * np.sum(displacement**2 * dkernel, axis=1)

        thermal = -(beta**2) * sigma_t / dt
        diffusive = sigma_d / dt

        return thermal, diffusive
